#!/usr/bin/env node
// Writes the Atlas as RDF (Turtle), from the curated data and the GitHub dataset.
//
//   node scripts/atlas-rdf.mjs [dataDir]        (default dataDir: site/data)
//
// Reads:
//   dataDir/atlas.json    hand-curated bodies, places, sectors (optional: GitHub alone then)
//   dataDir/github.json   from scripts/github-data.mjs (optional)
//   dataDir/github-detail.json   per-repo commit days, pull requests and issues (optional)
// Writes:
//   dataDir/atlas.ttl          the whole Atlas as Turtle, grouped and deterministic
//   dataDir/contributions.ttl  every PR, issue and commit day (large; loaded second by the console)
//   dataDir/atlas.js           `window.ATLAS = <atlas.json>` (regenerated only when out of date)
//
// Vocabulary: site/DATA.md ("RDF vocabulary"). Dependency-free; Node 18+.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dataDir = process.argv[2] || "site/data";
const readJson = (name) => {
  const file = join(dataDir, name);
  return existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : null;
};
const atlas = readJson("atlas.json");
const github = readJson("github.json");
const detail = readJson("github-detail.json");
if (!atlas && !github) {
  console.error(`atlas-rdf: neither atlas.json nor github.json in ${dataDir}`);
  process.exit(1);
}

// ── Turtle writing helpers ───────────────────────────────────────────────────
const PREFIXES = {
  "": "https://yrashk.com/atlas/",
  yr: "https://yrashk.com/ns#",
  schema: "https://schema.org/",
  xsd: "http://www.w3.org/2001/XMLSchema#",
  rdfs: "http://www.w3.org/2000/01/rdf-schema#",
};
// A prefixed name needs a safe local part (no "/": Turtle forbids it unescaped); else <…>.
const PN_LOCAL = /^[A-Za-z0-9_][A-Za-z0-9_\-.]*$/;
const node = (id) => (PN_LOCAL.test(id) && !/\.$/.test(id) ? `:${id}` : `<${PREFIXES[""]}${id}>`);
const sectorNode = (id) => `<${PREFIXES[""]}sector/${id}>`;
const str = (s) =>
  `"${String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n").replace(/\r/g, "\\r").replace(/\t/g, "\\t")}"`;
const iri = (u) => `<${String(u).replace(/[<>"{}|^`\\\s]/g, (c) => encodeURIComponent(c))}>`;
const gYear = (y) => `"${y}"^^xsd:gYear`;
const date = (d) => `"${d}"^^xsd:date`;
const int = (n) => String(Math.trunc(n));
const dec = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));

let out = [];
const comment = (text) => out.push(`# ${text}`);
const blank = () => out.push("");
// One subject, its predicate-object pairs (objects may be arrays), pretty-printed.
function subject(s, pairs) {
  const lines = [];
  for (const [p, o] of pairs) {
    // `false` is how a pair opts out (`cond && value`); boolean literals are passed as "true"/"false".
    const objs = (Array.isArray(o) ? o : [o]).filter((v) => v !== undefined && v !== null && v !== "" && v !== false);
    if (!objs.length) continue;
    lines.push(`    ${p.padEnd(26)} ${objs.join(", ")}`);
  }
  if (!lines.length) return;
  out.push(`${s}\n${lines.join(" ;\n")} .`);
  blank();
}
// An inline blank node: [ p o ; p o ].
const bnode = (pairs) => `[ ${pairs.map(([p, o]) => `${p} ${o}`).join(" ; ")} ]`;

// ── header ───────────────────────────────────────────────────────────────────
function header(what, base = false) {
  comment(`${what} Generated by scripts/atlas-rdf.mjs; do not edit.`);
  comment("Vocabulary: site/DATA.md. Query it in the Lab (SPARQL console) or with any RDF tool.");
  blank();
  if (base) out.push(`@base <${PREFIXES[""]}> .`);
  for (const [p, ns] of Object.entries(PREFIXES)) out.push(`@prefix ${(p + ":").padEnd(7)} <${ns}> .`);
  blank();
}
header("The Atlas of yrashk.com as RDF.");

const KIND = {
  life: { classes: ["yr:LifeEvent", "schema:Event"], role: "yr:lived", title: "Life" },
  company: { classes: ["yr:Company", "schema:Organization"], role: "yr:founded", title: "Companies" },
  project: { classes: ["yr:Project", "schema:CreativeWork"], role: "yr:built", title: "Projects" },
  writing: { classes: ["yr:Essay", "schema:BlogPosting"], role: "yr:wrote", title: "Writing" },
  idea: { classes: ["yr:Idea"], role: "yr:shelved", title: "Ideas" },
  oss: { classes: ["yr:Repository", "schema:SoftwareSourceCode"], role: "yr:contributedTo", title: "Open source (curated)" },
  talk: { classes: ["yr:Talk", "schema:Event"], role: "yr:presented", title: "Talks" },
};
// A talk's recording: a YouTube video (optionally a cut of a longer stream, by offsets) or a page elsewhere.
const recording = (v) => {
  if (!v) return null;
  if (v.yt) {
    const q = [v.start != null && `start=${v.start}`, v.end != null && `end=${v.end}`].filter(Boolean).join("&");
    return bnode([
      ["a", "schema:VideoObject"],
      ["schema:url", iri(`https://www.youtube.com/watch?v=${v.yt}${v.start ? `&t=${v.start}s` : ""}`)],
      ["schema:embedUrl", iri(`https://www.youtube-nocookie.com/embed/${v.yt}${q ? `?${q}` : ""}`)],
      ...(v.start != null ? [["yr:startOffset", int(v.start)]] : []),
      ...(v.end != null ? [["yr:endOffset", int(v.end)]] : []),
      ...(v.dur != null ? [["yr:seconds", int(v.dur)]] : []),
      ...(v.title ? [["schema:name", str(v.title)]] : []),
      // a whole event stream: one schema:Clip per talk, at its offset into the video
      ...(v.chapters ?? []).map((c) => [
        "schema:hasPart",
        bnode([
          ["a", "schema:Clip"],
          ["schema:name", str(c.title)],
          ["schema:startOffset", int(c.t)],
          ...(c.speaker ? [["yr:speaker", str(c.speaker)]] : []),
          ...(c.talk ? [["yr:talk", node(c.talk)]] : []),
        ]),
      ]),
    ]);
  }
  return v.href ? bnode([["a", "schema:VideoObject"], ["schema:url", iri(v.href)], ...(v.host ? [["yr:host", str(v.host)]] : [])]) : null;
};
const SITE = "https://yrashk.com";
const absolute = (u) => (u && u.startsWith("/") ? SITE + u : u);

// A place whose id is also a body id would share its IRI: such a place lives under place/.
const bodyIds = new Set((atlas?.bodies ?? []).map((b) => b.id));
const warned = new Set();
const placeNode = (id) => {
  if (!bodyIds.has(id)) return node(id);
  if (!warned.has(id)) console.warn(`atlas-rdf: place "${id}" has the same id as a body; writing it as <…/place/${id}> (rename one of them)`);
  warned.add(id);
  return `<${PREFIXES[""]}place/${id}>`;
};

// Which repos belong to a curated body, so the person's role links point at the body.
const repoBody = new Map();
for (const b of atlas?.bodies ?? []) for (const r of b.github ?? []) repoBody.set(r.toLowerCase(), b.id);
const repoNode = (fullName) => `<${PREFIXES[""]}repo/${fullName}>`;

// ── person, places, sectors ──────────────────────────────────────────────────
if (atlas) {
  const P = atlas.person;
  const bodies = atlas.bodies ?? [];
  const byKind = (k, only = () => true) => bodies.filter((b) => b.kind === k && only(b)).map((b) => node(b.id));
  comment(`── ${P.name} ──`);
  blank();
  subject(node(P.id), [
    ["a", "schema:Person"],
    ["schema:name", str(P.name)],
    ["schema:url", iri(SITE)],
    ["schema:birthDate", P.born && gYear(P.born)],
    ["schema:birthPlace", atlas.places?.some((pl) => pl.id === P.birthplace?.toLowerCase()) ? placeNode(P.birthplace.toLowerCase()) : P.birthplace && str(P.birthplace)],
    ["schema:homeLocation", (P.homes ?? []).map(placeNode)],
    ["yr:currentLocation", (P.homes ?? []).includes(P.here) && placeNode(P.here)], // where he is now (person.here)
    ["yr:lived", byKind("life")],
    ["yr:founded", byKind("company", (b) => !b.role || b.role === "founder")],
    ["yr:workedAt", byKind("company", (b) => b.role && b.role !== "founder")],
    ["yr:built", byKind("project")],
    ["yr:wrote", byKind("writing")],
    ["yr:shelved", byKind("idea")],
    ["yr:authored", byKind("oss", (b) => b.role === "author")], // pre-GitHub work he wrote
    ["yr:contributedTo", byKind("oss", (b) => b.role !== "author")],
    ["yr:presented", byKind("talk")],
  ]);

  comment("── Places ──");
  blank();
  for (const pl of atlas.places ?? []) {
    subject(placeNode(pl.id), [
      ["a", "schema:Place"],
      ["schema:name", str(pl.name)],
      ["schema:geo", pl.lat != null && bnode([["schema:latitude", dec(pl.lat)], ["schema:longitude", dec(pl.lon)]])],
      ["yr:timeZone", pl.tz && str(pl.tz)],
    ]);
  }

  comment("── Sectors (the slices of the chart, in drawing order) ──");
  blank();
  (atlas.sectors ?? []).forEach((s, i) =>
    subject(sectorNode(s.id), [
      ["a", "yr:Sector"],
      ["rdfs:label", str(s.label)],
      ["yr:order", int(i + 1)],
    ]),
  );

  // ── bodies, grouped by kind ─────────────────────────────────────────────────
  for (const [kind, k] of Object.entries(KIND)) {
    const group = bodies.filter((b) => b.kind === kind);
    if (!group.length) continue;
    comment(`── ${k.title} ──`);
    blank();
    for (const b of group) {
      subject(node(b.id), [
        ["a", k.classes],
        ["schema:name", str(b.name)],
        ["schema:url", b.url && iri(absolute(b.url))],
        ["schema:description", b.line && str(b.line)],
        ["schema:abstract", b.desc && str(b.desc)],
        ["yr:quote", b.quote && str(b.quote)],
        ["yr:sector", b.sector && sectorNode(b.sector)],
        ["yr:start", b.start != null && gYear(b.start)],
        ["yr:end", b.end != null && gYear(b.end)],
        ["yr:approximate", b.approx ? "true" : null],
        ["yr:weight", b.weight != null && int(b.weight)],
        ["yr:role", b.role && str(b.role)],
        ["yr:status", b.status && str(b.status)],
        ["schema:datePublished", b.kind !== "talk" && b.date && date(b.date)],
        ["schema:startDate", b.kind === "talk" && b.date && date(b.date)],
        ["schema:superEvent", b.event && bnode([["a", "schema:Event"], ["schema:name", str(b.event)], ...(b.venue ? [["schema:location", str(b.venue)]] : [])])],
        ["yr:format", b.format && str(b.format)],
        ["yr:alsoAt", (b.also ?? []).map(str)],
        ["schema:recordedIn", recording(b.video)],
        ["yr:slides", b.slides && iri(b.slides)],
        ["yr:listed", b.kind === "writing" ? (b.listed ? "true" : "false") : null],
        ["schema:keywords", (b.tags ?? []).map(str)],
        ["schema:location", b.place && placeNode(b.place)],
        ["yr:related", (b.related ?? []).map(node)],
        ["yr:continuedAs", b.continuedAs && node(b.continuedAs)],
        ["yr:repo", (b.github ?? []).map(repoNode)],
      ]);
    }
  }
}

// ── GitHub ───────────────────────────────────────────────────────────────────
if (github) {
  const me = atlas ? node(atlas.person.id) : ":yrashk";
  const login = github.login || "yrashk";
  const full = (r) => (r.name.includes("/") ? r.name : `${r.org || login}/${r.name}`);
  const byName = (a, b) => full(a).toLowerCase().localeCompare(full(b).toLowerCase());
  const authored = [...github.authored].sort(byName);
  const contributed = [...github.contributed].sort(byName);

  comment(`── GitHub (${github.generated?.slice(0, 10) ?? "snapshot"}): ${authored.length} authored, ${contributed.length} contributed ──`);
  blank();
  subject(me, [
    ["schema:sameAs", iri(`https://github.com/${login}`)],
    ["yr:githubSince", github.profile?.since && date(github.profile.since)],
    ["yr:followers", github.profile?.followers != null && int(github.profile.followers)],
    ["yr:authored", authored.map((r) => repoNode(full(r)))],
    ["yr:contributedTo", contributed.map((r) => repoNode(full(r)))],
  ]);

  const activity = (r) =>
    Object.keys(r.years ?? {})
      .sort()
      .map((y) => bnode([["yr:year", gYear(y)], ["yr:contributions", int(r.years[y])]]));

  const repo = (r) => {
    const name = full(r);
    const owner = name.split("/")[0];
    subject(repoNode(name), [
      ["a", ["yr:Repository", "schema:SoftwareSourceCode"]],
      ["schema:name", str(name)],
      ["schema:codeRepository", iri(r.url || `https://github.com/${name}`)],
      ["schema:url", r.homepage && iri(r.homepage)],
      ["schema:description", r.description && str(r.description)],
      ["schema:programmingLanguage", r.language && str(r.language)],
      ["yr:stars", r.stars != null && int(r.stars)],
      ["yr:organization", owner.toLowerCase() !== login.toLowerCase() ? str(owner) : null],
      ["yr:archived", r.archived ? "true" : null],
      ["schema:dateCreated", r.created && date(r.created)],
      ["yr:start", r.first != null && gYear(r.first)],
      ["yr:end", r.last != null && gYear(r.last)],
      ["yr:body", repoBody.has(name.toLowerCase()) && node(repoBody.get(name.toLowerCase()))],
      ["yr:activity", activity(r)],
    ]);
  };

  comment("── Authored repositories (owned, or organization repositories led) ──");
  blank();
  for (const r of authored) repo(r);
  comment("── Repositories contributed to ──");
  blank();
  for (const r of contributed) repo(r);
}

const finish = () => out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
const ttl = finish();
writeFileSync(join(dataDir, "atlas.ttl"), ttl);

// ── contributions: PRs, issues and commit days, as their own document ────────
let detailStats = "";
if (detail?.repos) {
  out = [];
  header("Contributions on GitHub: pull requests, issues and commit days.", true);
  // Relative to @base: <repo/owner/name/pull/1> is <https://yrashk.com/atlas/repo/owner/name/pull/1>.
  const rel = (path) => `<${path}>`;
  const me = atlas ? node(atlas.person.id) : ":yrashk";
  const login = (github?.login || detail.login || "yrashk").toLowerCase();
  const known = new Set();
  for (const r of github?.authored ?? []) known.add((r.name.includes("/") ? r.name : `${r.org || login}/${r.name}`).toLowerCase());
  for (const r of github?.contributed ?? []) known.add(r.name.toLowerCase());
  const names = Object.keys(detail.repos).sort((a, b) => a.toLowerCase().localeCompare(b.toLowerCase()));
  const prOf = (repo, n) => rel(`repo/${repo}/pull/${n}`);
  const issueOf = (repo, n) => rel(`repo/${repo}/issues/${n}`);
  const repoRel = (repo) => rel(`repo/${repo}`);
  const byDate = (a, b) => (a[3] < b[3] ? -1 : a[3] > b[3] ? 1 : a[0] - b[0]);
  let prs = 0, issues = 0, days = 0, extra = 0;
  const newRepos = names.filter((n) => !known.has(n.toLowerCase()));
  comment(`── ${names.length} repositories; ${newRepos.length} appear here only (pull requests or issues, no commits counted) ──`);
  blank();
  subject(me, [
    ["yr:contributedTo", newRepos.map(repoRel)],
    ["yr:opened", names.flatMap((n) => [...(detail.repos[n].prs ?? []).sort(byDate).map((p) => prOf(n, p[0])), ...(detail.repos[n].issues ?? []).sort(byDate).map((i) => issueOf(n, i[0]))])],
  ]);
  for (const name of names) {
    const r = detail.repos[name];
    const owner = name.split("/")[0];
    const fresh = !known.has(name.toLowerCase());
    if (fresh) extra++;
    const dayNodes = [...(r.days ?? [])].sort((a, b) => (a[0] < b[0] ? -1 : 1)).map(([d, n]) => bnode([["schema:startDate", date(d)], ["yr:commits", int(n)]]));
    days += dayNodes.length;
    subject(repoRel(name), [
      ["a", fresh ? ["yr:Repository", "schema:SoftwareSourceCode"] : null],
      ["schema:name", fresh ? str(name) : null],
      ["schema:codeRepository", fresh ? iri(`https://github.com/${name}`) : null],
      ["yr:organization", fresh && owner.toLowerCase() !== login ? str(owner) : null],
      ["yr:commitDay", dayNodes],
    ]);
    for (const [n, title, state, d] of [...(r.prs ?? [])].sort(byDate)) {
      prs++;
      subject(prOf(name, n), [
        ["a", ["yr:PullRequest", "schema:CreativeWork"]],
        ["yr:repository", repoRel(name)],
        ["yr:number", int(n)],
        ["schema:name", str(title)],
        ["yr:state", str(state)],
        ["schema:dateCreated", d && date(d)],
        ["schema:url", iri(`https://github.com/${name}/pull/${n}`)],
      ]);
    }
    for (const [n, title, state, d] of [...(r.issues ?? [])].sort(byDate)) {
      issues++;
      subject(issueOf(name, n), [
        ["a", "yr:Issue"],
        ["yr:repository", repoRel(name)],
        ["yr:number", int(n)],
        ["schema:name", str(title)],
        ["yr:state", str(state)],
        ["schema:dateCreated", d && date(d)],
        ["schema:url", iri(`https://github.com/${name}/issues/${n}`)],
      ]);
    }
  }
  const cttl = finish();
  writeFileSync(join(dataDir, "contributions.ttl"), cttl);
  detailStats = `; ${prs} PRs, ${issues} issues, ${days} commit days → contributions.ttl (${(cttl.length / 1024).toFixed(0)} KiB)`;
}

// atlas.js mirrors atlas.json so pages work over file://.
if (atlas) {
  const js = `// Hand-curated Atlas data (see DATA.md). Keep in sync with atlas.json.\nwindow.ATLAS = ${JSON.stringify(atlas)};\n`;
  const file = join(dataDir, "atlas.js");
  if (!existsSync(file) || readFileSync(file, "utf8") !== js) writeFileSync(file, js);
}

const triples = (ttl.match(/ \.\n/g) || []).length;
console.log(
  `atlas-rdf: ${atlas?.bodies?.length ?? 0} bodies, ${github?.authored?.length ?? 0} authored + ${github?.contributed?.length ?? 0} contributed repos ` +
    `→ ${join(dataDir, "atlas.ttl")} (${triples} subjects, ${(ttl.length / 1024).toFixed(0)} KiB)${detailStats}`,
);
